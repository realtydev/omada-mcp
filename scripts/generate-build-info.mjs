// Generates src/generated/buildInfo.ts before every `tsc` build, so the running server can report
// which commit and package version it was actually built from (see getServerInfo). This exists
// because an MCP stdio server keeps running whatever code it loaded at connection time — rebuilding
// dist/ on disk does not affect an already-running process, only a fresh connection does — and there
// was previously no way for a session to tell whether the server it's talking to matches the source
// it's reading. Never imported by anything other than src/server/common.ts.
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

function run(command) {
    try {
        return execSync(command, { cwd: repoRoot, stdio: ['ignore', 'pipe', 'ignore'] })
            .toString()
            .trim();
    } catch {
        return undefined;
    }
}

const packageVersion = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')).version;
const commit = run('git rev-parse --short HEAD') ?? 'unknown';
const dirty = run('git status --porcelain');
const gitCommit = dirty ? `${commit}-dirty` : commit;
const buildTime = new Date().toISOString();

const outDir = join(repoRoot, 'src', 'generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(
    join(outDir, 'buildInfo.ts'),
    `// Generated by scripts/generate-build-info.mjs during \`yarn build\` — do not edit, do not commit.
export const PACKAGE_VERSION = ${JSON.stringify(packageVersion)};
export const GIT_COMMIT = ${JSON.stringify(gitCommit)};
export const BUILD_TIME = ${JSON.stringify(buildTime)};
`
);
